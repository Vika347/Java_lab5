package managers;

import java.util.concurrent.atomic.AtomicInteger;

/**
 * Генератор уникальных идентификаторов для объектов {@code LabWork}.
 * <p>
 * Обеспечивает последовательную выдачу уникальных идентификаторов
 * и возможность инициализации счётчика существующим максимальным значением.
 * Для хранения значения используется потокобезопасный класс
 * {@link AtomicInteger}, обеспечивающий атомарность операций.
 * </p>
 *
 * @author Виктория Родина
 */
public class IdGenerator {

    /**
     * Счётчик идентификаторов.
     * <p>
     * Хранит текущее значение последнего выданного идентификатора.
     * Использование {@link AtomicInteger} обеспечивает потокобезопасность.
     * </p>
     */
    private static final AtomicInteger counter = new AtomicInteger(0); //(Потокобезопасен, операции атомарны)

    /**
     * Возвращает следующий уникальный идентификатор.
     * <p>
     * Значение счётчика увеличивается на единицу перед возвратом.
     * </p>
     *
     * @return следующий уникальный идентификатор
     */
    public static int nextId() {
        return counter.incrementAndGet();
    }

    /**
     * Инициализирует счётчик идентификаторов.
     * <p>
     * Используется при загрузке коллекции для установки значения
     * счётчика равным максимальному существующему идентификатору.
     * Следующий вызов {@link #nextId()} вернёт значение,
     * большее указанного.
     * </p>
     *
     * @param maxId максимальный существующий идентификатор
     */
    public static void init(int maxId) {
        counter.set(maxId);
    }
}