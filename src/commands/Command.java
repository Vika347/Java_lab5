package commands;

/**
 * Интерфейс команды.
 * <p>
 * Все команды приложения должны реализовывать данный интерфейс.
 * Каждая команда обязана иметь имя, описание и поддерживать выполнение
 * с переданными аргументами.
 * </p>
 *
 * @author Виктория Родина
 */
public interface Command {

    /**
     * Возвращает имя команды.
     *
     * @return имя команды
     */
    String getName();

    /**
     * Возвращает описание команды.
     * Описание используется для вывода справки по доступным командам.
     *
     * @return описание команды
     */
    String getDescription();

    /**
     * Выполняет команду.
     *
     * @param arguments массив аргументов команды.
     *                  Если команда не принимает аргументы,
     *                  массив может быть пустым.
     */
    void execute(String[] arguments);
}